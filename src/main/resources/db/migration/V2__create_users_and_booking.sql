CREATE TABLE users (
                       id    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                       email VARCHAR(255) NOT NULL UNIQUE,
                       name  VARCHAR(120) NOT NULL
);

CREATE TABLE bookings (
                          id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                          resource_id BIGINT NOT NULL,
                          user_id     BIGINT NOT NULL,
                          starts_at   TIMESTAMP WITH TIME ZONE NOT NULL,
                          ends_at     TIMESTAMP WITH TIME ZONE NOT NULL,
                          created_at  TIMESTAMP WITH TIME ZONE NOT NULL,

                          CONSTRAINT fk_bookings_resource FOREIGN KEY (resource_id) REFERENCES resources (id),
                          CONSTRAINT fk_bookings_user     FOREIGN KEY (user_id)     REFERENCES users (id),
                          CONSTRAINT chk_bookings_period  CHECK (ends_at > starts_at)
);

CREATE INDEX idx_bookings_resource_period ON bookings (resource_id, starts_at, ends_at);